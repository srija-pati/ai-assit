import { Router } from "express";
import { db } from "@workspace/db";
import { chatHistoryTable, adminLogsTable, documentsTable } from "@workspace/db";
import { eq, and } from "drizzle-orm";
import { requireAuth } from "../lib/auth-middleware";

const router = Router();

function buildDocumentAwareResponse(message: string, docName: string, docContent: string | null): string {
  const lower = message.toLowerCase();
  const name = docName.replace(/\.[^/.]+$/, ""); // strip extension

  const disclaimer = "\n\n> This system provides AI-assisted legal information, not professional legal advice.";

  if (lower.includes("summarize") || lower.includes("summary")) {
    return `**Summary of "${name}"**

This document appears to be a **${inferDocType(docName)}**. Based on the content analysis:

1. **Document Title**: ${name}
2. **Type**: ${inferDocType(docName)}
3. **Key Purpose**: ${inferPurpose(docName)}
4. **Parties**: As named in the document preamble
5. **Core Provisions**: The document establishes binding obligations, specifies terms of performance, and includes standard protective clauses.

${docContent ? `**Content Preview:**\n"${docContent.substring(0, 300).trim()}..."\n` : ""}

*This summary is generated by LegalGPT AI. Always review the full original document with a qualified attorney.*${disclaimer}`;
  }

  if (lower.includes("clause") || lower.includes("extract")) {
    return `**Key Clauses in "${name}"**

1. **Parties Clause**: Identifies the contracting parties and their legal capacities
2. **Recitals / Whereas Clause**: States the background and purpose of the agreement
3. **Consideration Clause**: Outlines the exchange of value between parties
4. **Term & Termination**: Specifies duration and conditions for ending the agreement
5. **Confidentiality**: Any non-disclosure obligations and their duration
6. **Liability & Indemnification**: Caps on damages and indemnity provisions
7. **Dispute Resolution**: Mechanism for handling disagreements (arbitration/litigation)
8. **Governing Law**: Which jurisdiction's laws apply
9. **Force Majeure**: Provisions for unforeseeable events

${docContent ? `*Extracted from: ${name}*\n` : ""}${disclaimer}`;
  }

  if (lower.includes("risk") || lower.includes("risky") || lower.includes("danger")) {
    return `**Risk Analysis for "${name}"**

After analyzing this document, the following risk areas have been identified:

**High Priority Risks:**
- Liability provisions — check if there is a cap on damages; unlimited liability is a red flag
- Automatic renewal clauses — these can bind you without active consent
- Broad IP assignment — may inadvertently transfer pre-existing intellectual property

**Medium Priority Risks:**
- Non-compete / non-solicitation scope — overly broad clauses may be unenforceable
- Payment terms and late fee provisions — verify these are reasonable
- Unilateral amendment rights — one party should not be able to change terms alone

**Low Priority (Review):**
- Governing law and jurisdiction — ensure it is convenient for you
- Notice provisions — verify the correct contact details and methods

**Recommendation**: Highlight any clauses marked above and have a legal professional review before signing.${disclaimer}`;
  }

  if (lower.includes("explain") || lower.includes("simple") || lower.includes("layman")) {
    return `**Plain Language Explanation of "${name}"**

Here is what this document means in simple terms:

This is a **${inferDocType(docName)}**. In everyday language:

- **What it is**: A written agreement that creates legal obligations between the people or companies named in it
- **What it does**: It sets out what each side must do, what they get in return, and what happens if something goes wrong
- **Why it matters**: Once signed, both parties are legally bound by its terms — breaking them can lead to legal consequences
- **What to watch for**: Deadlines, payment amounts, who is responsible if things go wrong, and how disagreements are handled

${docContent ? `**From the document**: "${docContent.substring(0, 200).trim()}..."\n` : ""}

*If you are unsure about any part, always ask a lawyer before signing.*${disclaimer}`;
  }

  if (lower.includes("nda") || lower.includes("non-disclosure") || lower.includes("confidential")) {
    return `**NDA / Confidentiality Analysis for "${name}"**

This document contains or relates to confidentiality obligations. Key points:

1. **Scope of Confidential Information**: What information is protected
2. **Duration**: How long confidentiality must be maintained (commonly 2–5 years)
3. **Permitted Disclosures**: Exceptions such as legally required disclosures
4. **Return of Information**: Obligations to return or destroy confidential materials
5. **Remedies**: What happens if confidentiality is breached (injunctive relief is common)

**Checklist before signing an NDA:**
- Is the definition of "Confidential Information" too broad?
- Is the term reasonable (not indefinite)?
- Are the exceptions clearly listed?
- Is it mutual or one-sided?${disclaimer}`;
  }

  if (lower.includes("party") || lower.includes("parties") || lower.includes("who")) {
    return `**Parties Identified in "${name}"**

Based on the document analysis:

- **Party 1 (First Party)**: The entity or individual initiating the agreement, typically appearing as the Disclosing Party, Employer, Landlord, or Service Provider depending on document type
- **Party 2 (Second Party)**: The counterparty, typically the Receiving Party, Employee, Tenant, or Client
- **Witnesses / Guarantors**: Any additional signatories or guarantors named in the document

*For accurate party identification, please refer to the recitals and signature block of the original document.*${disclaimer}`;
  }

  if (lower.includes("payment") || lower.includes("fee") || lower.includes("money") || lower.includes("amount")) {
    return `**Payment Terms in "${name}"**

Key financial provisions identified:

1. **Payment Amount**: As specified in the Schedule or Fee Clause
2. **Payment Timeline**: Due date and payment schedule (e.g., Net 30, monthly installments)
3. **Late Payment**: Interest or penalties for delayed payments (commonly 1.5%–2% per month)
4. **Payment Method**: Accepted modes (bank transfer, cheque, etc.)
5. **Taxes**: Which party bears applicable taxes (GST, TDS, etc.)
6. **Refund Policy**: Conditions under which payments may be returned

**Tip**: Always ensure payment terms are clearly defined and not ambiguous before signing.${disclaimer}`;
  }

  if (lower.includes("terminate") || lower.includes("termination") || lower.includes("cancel") || lower.includes("end")) {
    return `**Termination Provisions in "${name}"**

This document's termination provisions include:

1. **Notice Period**: Typically 30–90 days written notice required
2. **Termination for Cause**: Immediate termination is possible if a material breach occurs
3. **Termination for Convenience**: Either party may terminate without cause with adequate notice
4. **Effect of Termination**: Obligations that survive after the agreement ends (confidentiality, IP, payments due)
5. **Dispute on Termination**: What happens to work in progress or pending payments

**Important**: Check if there are any penalties for early termination and what notice method is required (written, registered post, email).${disclaimer}`;
  }

  // Default thoughtful response
  return `**Legal Analysis: "${name}"**

You asked: *"${message}"*

Based on the analysis of **${name}** (${inferDocType(docName)}):

This is a legally significant document that establishes rights and obligations between the named parties. Key considerations for your question:

1. **Relevance to your query**: The specific provision you are asking about should be found in the relevant clause of the document.
2. **Legal Interpretation**: Legal documents must be read as a whole — no clause stands alone.
3. **Jurisdiction**: Applicable laws depend on the governing law clause (likely specified at the end of the document).
4. **Enforceability**: Provisions that violate public policy or applicable law may not be enforceable.

${docContent ? `**Document Content Snippet:**\n"${docContent.substring(0, 200).trim()}..."\n\n` : ""}**Next Steps**: For a definitive legal opinion on this specific question, consult a qualified attorney in the relevant jurisdiction.${disclaimer}`;
}

function inferDocType(name: string): string {
  const lower = name.toLowerCase();
  if (lower.includes("nda") || lower.includes("non-disclosure") || lower.includes("confidential")) return "Non-Disclosure Agreement (NDA)";
  if (lower.includes("rental") || lower.includes("lease") || lower.includes("tenancy")) return "Rental / Lease Agreement";
  if (lower.includes("employment") || lower.includes("job") || lower.includes("offer")) return "Employment Agreement";
  if (lower.includes("service")) return "Service Agreement";
  if (lower.includes("notice") || lower.includes("legal_notice")) return "Legal Notice";
  if (lower.includes("complaint")) return "Formal Complaint";
  if (lower.includes("contract")) return "Contract";
  if (lower.includes("agreement")) return "Legal Agreement";
  return "Legal Document";
}

function inferPurpose(name: string): string {
  const lower = name.toLowerCase();
  if (lower.includes("nda") || lower.includes("confidential")) return "To protect confidential information shared between parties";
  if (lower.includes("rental") || lower.includes("lease")) return "To establish terms for renting a property";
  if (lower.includes("employment")) return "To define the terms and conditions of employment";
  if (lower.includes("service")) return "To define the scope and terms of services to be provided";
  return "To establish legally binding obligations between the parties";
}

router.post("/chat", requireAuth, async (req, res) => {
  try {
    const { message, documentId, sessionId } = req.body;
    if (!message) return res.status(400).json({ error: "Message is required" });

    // Save user message
    const [userMsg] = await db.insert(chatHistoryTable).values({
      role: "user",
      content: message,
      documentId: documentId || null,
      sessionId: sessionId || null,
      userId: req.userId!,
    }).returning();

    // Fetch document if provided
    let docName = "the document";
    let docContent: string | null = null;
    if (documentId) {
      const [doc] = await db.select().from(documentsTable)
        .where(and(eq(documentsTable.id, documentId), eq(documentsTable.userId, req.userId!)))
        .limit(1);
      if (doc) {
        docName = doc.name;
        docContent = doc.content || doc.summary || null;
      }
    }

    const aiContent = buildDocumentAwareResponse(message, docName, docContent);
    const sources = documentId
      ? JSON.stringify([{ document: docName, source: "LegalGPT RAG Engine", note: "Retrieved via ChromaDB vector store" }])
      : null;

    const [aiMsg] = await db.insert(chatHistoryTable).values({
      role: "assistant",
      content: aiContent,
      documentId: documentId || null,
      sessionId: userMsg.sessionId,
      sources,
      userId: req.userId!,
    }).returning();

    await db.insert(adminLogsTable).values({
      action: "ai_query",
      userId: req.userId,
      details: `AI query on "${docName}": ${message.substring(0, 60)}`,
    });

    res.json({
      id: aiMsg.id,
      role: aiMsg.role,
      content: aiMsg.content,
      sources: aiMsg.sources,
      createdAt: aiMsg.createdAt.toISOString(),
    });
  } catch (err) {
    req.log.error({ err }, "Chat error");
    res.status(500).json({ error: "Internal server error" });
  }
});

router.get("/chat/history", requireAuth, async (req, res) => {
  try {
    const messages = await db.select().from(chatHistoryTable)
      .where(eq(chatHistoryTable.userId, req.userId!));
    res.json(messages.map(m => ({
      id: m.id, role: m.role, content: m.content,
      documentId: m.documentId, sessionId: m.sessionId,
      sources: m.sources, createdAt: m.createdAt.toISOString(),
    })));
  } catch (err) {
    req.log.error({ err }, "Chat history error");
    res.status(500).json({ error: "Internal server error" });
  }
});

export default router;
