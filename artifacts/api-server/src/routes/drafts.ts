function generateContent(documentType: string, data: Record<string, string>): string {
  const template = DOCUMENT_TEMPLATES[documentType];
  if (template) return template(data);

  return `${documentType.toUpperCase().replace(/_/g, " ")}

Date: ${data.date}
Between: ${data.clientName} and ${data.oppositeName}
Address: ${data.address}
Purpose: ${data.purpose}
Jurisdiction: ${data.jurisdiction}

${data.keyTerms ? `Key Terms:\n${data.keyTerms}\n` : ""}

This document was generated by LegalGPT AI. Please review with a qualified attorney before use.`;
}

function getTitle(documentType: string, clientName: string): string {
  const titles: Record<string, string> = {
    nda: "Non-Disclosure Agreement",
    rental_agreement: "Rental Agreement",
    employment_agreement: "Employment Agreement",
    service_agreement: "Service Agreement",
    legal_notice: "Legal Notice",
    formal_complaint: "Formal Complaint Letter",
    authorization_letter: "Authorization Letter",
    contract_summary: "Contract Summary",
  };
  return `${titles[documentType] || documentType} - ${clientName}`;
}

router.post("/generate-document", requireAuth, async (req, res) => {
  try {
    const { documentType, clientName, oppositeName, address, purpose, date, keyTerms, jurisdiction } = req.body;
    if (!documentType || !clientName || !oppositeName || !address || !purpose || !date || !jurisdiction) {
      return res.status(400).json({ error: "All required fields must be provided" });
    }

    const content = generateContent(documentType, { documentType, clientName, oppositeName, address, purpose, date, keyTerms: keyTerms || "", jurisdiction });
    const title = getTitle(documentType, clientName);

    const [draft] = await db.insert(generatedDraftsTable).values({
      documentType, title, content, clientName, oppositeName,
      address, purpose, jurisdiction,
      userId: req.userId!,
    }).returning();

    await db.insert(adminLogsTable).values({
      action: "document_generated",
      userId: req.userId,
      details: `Generated: ${title}`,
    });

    res.json({
      id: draft.id, documentType: draft.documentType, title: draft.title,
      content: draft.content, clientName: draft.clientName, oppositeName: draft.oppositeName,
      createdAt: draft.createdAt.toISOString(), userId: draft.userId,
    });
  } catch (err) {
    req.log.error({ err }, "Generate document error");
    res.status(500).json({ error: "Internal server error" });
  }
});

router.get("/drafts", requireAuth, async (req, res) => {
  try {
    const drafts = await db.select().from(generatedDraftsTable)
      .where(eq(generatedDraftsTable.userId, req.userId!));
    res.json(drafts.map(d => ({
      id: d.id, documentType: d.documentType, title: d.title,
      content: d.content, clientName: d.clientName, oppositeName: d.oppositeName,
      createdAt: d.createdAt.toISOString(), userId: d.userId,
    })));
  } catch (err) {
    req.log.error({ err }, "List drafts error");
    res.status(500).json({ error: "Internal server error" });
  }
});

router.get("/drafts/:id", requireAuth, async (req, res) => {
  try {
    const id = parseInt(req.params.id);
    const [draft] = await db.select().from(generatedDraftsTable)
      .where(and(eq(generatedDraftsTable.id, id), eq(generatedDraftsTable.userId, req.userId!)))
      .limit(1);
    if (!draft) return res.status(404).json({ error: "Draft not found" });
    res.json({
      id: draft.id, documentType: draft.documentType, title: draft.title,
      content: draft.content, clientName: draft.clientName, oppositeName: draft.oppositeName,
      createdAt: draft.createdAt.toISOString(), userId: draft.userId,
    });
  } catch (err) {
    req.log.error({ err }, "Get draft error");
    res.status(500).json({ error: "Internal server error" });
  }
});

router.delete("/drafts/:id", requireAuth, async (req, res) => {
  try {
    const id = parseInt(req.params.id);
    await db.delete(generatedDraftsTable)
      .where(and(eq(generatedDraftsTable.id, id), eq(generatedDraftsTable.userId, req.userId!)));
    res.json({ success: true, message: "Draft deleted" });
  } catch (err) {
    req.log.error({ err }, "Delete draft error");
    res.status(500).json({ error: "Internal server error" });
  }
});

export default router;
